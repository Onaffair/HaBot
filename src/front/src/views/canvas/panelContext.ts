// 自定义节点 (BaseNode) 与画布 (Canvas) 之间的解耦通道：
// 节点内点击「设置」图标时，通过注入的 openConfig(nodeId) 通知画布打开该节点的配置面板，
// 避免逐层透传事件，也无需节点感知画布内部状态。
// ============================================================================
import type { InjectionKey } from 'vue'

/** 打开指定节点配置面板的注入方法 */
export const OpenConfigKey: InjectionKey<(nodeId: string) => void> = Symbol('canvas:openConfig')
